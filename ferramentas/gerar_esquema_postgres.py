"""Gera o esquema do Postgres (Supabase) a partir do esquema atual do SQLite.

Uso: python3 ferramentas/gerar_esquema_postgres.py > supabase/migrations/0001_esquema.sql

Cria um banco SQLite temporário com app.db.iniciar() (já com todas as migrações) e converte cada tabela:
  INTEGER PRIMARY KEY AUTOINCREMENT -> INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  REAL -> DOUBLE PRECISION          TEXT ... COLLATE NOCASE -> CITEXT
As tabelas saem na ordem das chaves estrangeiras. Todas ficam com RLS ligada e sem política: só a função de servidor (chave de serviço) acessa.
"""
import os, re, sys, tempfile
from pathlib import Path

tmp = Path(tempfile.mkdtemp()) / "esquema.db"
os.environ["ORCAMENTO_DB"] = str(tmp)
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app import db  # noqa: E402

db.iniciar()
con = db.conectar()
tabelas = {r[0]: r[1] for r in con.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}
indices = [r[0] for r in con.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%'")]


def converter(sql: str) -> str:
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    saida = []
    for linha in sql.split("\n"):
        if "COLLATE NOCASE" in linha:
            linha = linha.replace(" COLLATE NOCASE", "").replace("COLLATE NOCASE", "")
            linha = re.sub(r"\bTEXT\b", "CITEXT", linha, count=1)
        saida.append(linha)
    return "\n".join(saida)


# ordem: uma tabela depois das que ela referencia (autorreferência e ciclos não contam)
dep = {t: set(re.findall(r"REFERENCES\s+(\w+)", s)) - {t} for t, s in tabelas.items()}
ordem, feitas = [], set()
while len(ordem) < len(tabelas):
    prontas = [t for t in tabelas if t not in feitas and dep[t] <= feitas]
    if not prontas:
        raise SystemExit("Ciclo entre tabelas: " + ", ".join(t for t in tabelas if t not in feitas))
    for t in sorted(prontas):
        ordem.append(t); feitas.add(t)

print("-- Esquema do Orçamento Sekita para o Supabase (Postgres). Gerado por ferramentas/gerar_esquema_postgres.py; não edite à mão.")
print("CREATE EXTENSION IF NOT EXISTS citext;\n")
for t in ordem:
    print(converter(tabelas[t]).rstrip().rstrip(";") + ";\n")
for i in indices:
    print(i.rstrip().rstrip(";") + ";")
print("\n-- Segurança: o acesso é só pela função de servidor (chave de serviço); ninguém acessa as tabelas direto pelo navegador.")
for t in ordem:
    print(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;")
