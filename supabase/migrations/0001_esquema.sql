-- Esquema do Orçamento Sekita para o Supabase (Postgres). Gerado por ferramentas/gerar_esquema_postgres.py; não edite à mão.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE auditoria(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quando TEXT NOT NULL,
  autor TEXT NOT NULL,
  versao_id INTEGER,
  acao TEXT NOT NULL,
  detalhe TEXT
);

CREATE TABLE bp_linhas(                 -- estrutura do balanço (BP Sintético do Fechamento Contábil)
  codigo TEXT PRIMARY KEY,
  nome TEXT NOT NULL,
  pai TEXT NOT NULL DEFAULT '',
  tipo TEXT NOT NULL DEFAULT 'account',     -- group | account
  ordem INTEGER NOT NULL DEFAULT 0,
  ativa INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE culturas(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome CITEXT NOT NULL UNIQUE,
  grupo TEXT NOT NULL,
  unidade TEXT NOT NULL DEFAULT 'kg',        -- medida da produção: 'kg' (padrão), 'litro' (ex.: leite) ou 'uni' (unidade)
  embalagem TEXT NOT NULL DEFAULT '',        -- embalagem padrão (caixa, saco...); vazio = só na medida
  qtd_por_embalagem DOUBLE PRECISION NOT NULL DEFAULT 0, -- quantos kg (ou litros) cabem em uma embalagem (ex.: caixa de 20 kg)
  ativa INTEGER NOT NULL DEFAULT 1,
  estoque_destino TEXT NOT NULL DEFAULT 'produto' CHECK(estoque_destino IN ('produto','gado')),   -- linha do balanço que recebe o estoque do produto: Estoque de produtos acabados ou Estoque de gado de corte
  receita_tipo TEXT NOT NULL DEFAULT 'operacional' CHECK(receita_tipo IN ('operacional','nao_operacional')),   -- operacional: linha própria na DRE (receita e CPV); não operacional: vai para 'outras atividades'
  criado_em TEXT NOT NULL
);

CREATE TABLE divida_importacoes(      -- cada importação do 'Endividamento alterado.xlsx' é uma foto
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arquivo TEXT NOT NULL,
  importado_em TEXT NOT NULL,
  autor TEXT NOT NULL DEFAULT 'local',
  qtd_titulos INTEGER NOT NULL DEFAULT 0,
  qtd_abertos INTEGER NOT NULL DEFAULT 0,
  avisos TEXT NOT NULL DEFAULT ''
);

CREATE TABLE dre_importacao(            -- de onde veio a estrutura (uma linha só, a última)
  id INTEGER PRIMARY KEY CHECK(id=1),
  arquivo TEXT NOT NULL,
  importado_em TEXT NOT NULL,
  qtd_sinteticas INTEGER NOT NULL,
  qtd_analiticas INTEGER NOT NULL
);

CREATE TABLE dre_linhas(                -- estrutura da DRE trazida do Fechamento Contábil (cadastro único)
  codigo TEXT PRIMARY KEY,
  nivel TEXT NOT NULL CHECK(nivel IN ('sintetica','analitica')),
  nome TEXT NOT NULL,
  pai TEXT NOT NULL DEFAULT '',
  tipo TEXT NOT NULL DEFAULT 'account',     -- group | account
  ordem INTEGER NOT NULL DEFAULT 0,
  ativa INTEGER NOT NULL DEFAULT 1,
  destino TEXT NOT NULL DEFAULT ''          -- nas analíticas: código da linha sintética
);

CREATE TABLE grupos_custo(            -- cadastro único dos grupos de custos variáveis
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome CITEXT NOT NULL UNIQUE,
  classificacao TEXT NOT NULL CHECK(classificacao IN ('direto','indireto')),
  ativa INTEGER NOT NULL DEFAULT 1,
  criado_em TEXT NOT NULL
);

CREATE TABLE investimento_classificacoes(  -- classificação do investimento (Expansão, Manutenção...): cadastro único
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  ativa INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE premissas_dem(              -- premissas dos demonstrativos: cada uma cai em uma conta da DRE ou do balanço
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  demonstrativo TEXT NOT NULL,              -- dre | balanco
  nome CITEXT NOT NULL,
  conta_codigo TEXT NOT NULL,
  sinal INTEGER NOT NULL DEFAULT 1,         -- 1 soma na conta; -1 subtrai (despesa na DRE)
  tipo TEXT NOT NULL DEFAULT 'valor',       -- valor | percentual (percentual de um campo base do demonstrativo)
  base_codigo TEXT NOT NULL DEFAULT '',     -- no tipo percentual: a linha do demonstrativo sobre a qual o % incide
  base_negativa TEXT NOT NULL DEFAULT 'calcular',  -- percentual com base negativa: calcular (gera valor com o sinal invertido) | zerar
  criada_em TEXT NOT NULL,
  UNIQUE(demonstrativo, nome)
);

CREATE TABLE realizado(                    -- linhas dos demonstrativos realizados, em R$
  ano INTEGER NOT NULL,
  demonstrativo TEXT NOT NULL,
  codigo TEXT NOT NULL,
  nome TEXT NOT NULL DEFAULT '',
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(ano, demonstrativo, codigo)
);

CREATE TABLE realizado_anos(               -- anos fechados importados (Balanço e DRE realizados, uma vez só, vale para todas as versões)
  ano INTEGER NOT NULL,
  demonstrativo TEXT NOT NULL,              -- BP | DRE
  arquivo TEXT NOT NULL,
  importado_em TEXT NOT NULL,
  importado_por TEXT NOT NULL,
  PRIMARY KEY(ano, demonstrativo)
);

CREATE TABLE realizado_parcial(
  ano INTEGER NOT NULL,
  demonstrativo TEXT NOT NULL,              -- BP | DRE
  codigo TEXT NOT NULL,
  nome TEXT NOT NULL DEFAULT '',
  valor DOUBLE PRECISION NOT NULL,                      -- R$
  PRIMARY KEY(ano, demonstrativo, codigo)
);

CREATE TABLE realizado_parcial_anos(       -- ano ainda em andamento (ex.: jan a jun de 2026): só consulta e indicadores, não alimenta o orçamento
  ano INTEGER PRIMARY KEY,
  meses INTEGER NOT NULL,                   -- meses fechados (a DRE é do início do ano até aqui; o balanço é do último dia do período)
  arquivo TEXT NOT NULL,
  importado_em TEXT NOT NULL,
  importado_por TEXT NOT NULL
, mes_inicio INTEGER NOT NULL DEFAULT 1, versao_id INTEGER);

CREATE TABLE divida_titulos(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  importacao_id INTEGER NOT NULL REFERENCES divida_importacoes(id) ON DELETE CASCADE,
  situacao TEXT NOT NULL,                 -- AB = aberto, PG = pago
  empresa TEXT NOT NULL DEFAULT '',       -- sigla: MESO, AFAL, ST, TAL...
  tipo TEXT NOT NULL DEFAULT '',          -- Custeio, Capital de Giro, Investimento, EGF
  grupo TEXT NOT NULL,                    -- capital_giro | investimento | indefinido
  banco TEXT NOT NULL DEFAULT '',
  tipo_recurso TEXT NOT NULL DEFAULT '',
  linha_credito TEXT NOT NULL DEFAULT '',
  documento TEXT NOT NULL DEFAULT '',
  contrato TEXT NOT NULL DEFAULT '',      -- documento sem o sufixo "/n"
  taxa DOUBLE PRECISION,                              -- ao ano (0,12 = 12%)
  data_operacao TEXT,
  data_vencimento TEXT,
  principal DOUBLE PRECISION NOT NULL DEFAULT 0,
  juros DOUBLE PRECISION NOT NULL DEFAULT 0,
  outras_despesas DOUBLE PRECISION NOT NULL DEFAULT 0,
  bruto DOUBLE PRECISION NOT NULL DEFAULT 0,
  produto TEXT NOT NULL DEFAULT '',
  observacao TEXT NOT NULL DEFAULT ''
);

CREATE TABLE investimento_tipos(           -- tipos de investimento ou desinvestimento, cadastro único (vale para todas as versões)
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  natureza TEXT NOT NULL,                   -- investimento | desinvestimento
  conta_codigo TEXT NOT NULL,               -- conta padrão do balanço (ativo)
  classificacao_id INTEGER NOT NULL REFERENCES investimento_classificacoes(id),
  carrega_saldo INTEGER NOT NULL DEFAULT 0, -- só investimento: traz o saldo a realizar do ano anterior
  vida_util DOUBLE PRECISION NOT NULL DEFAULT 0,        -- anos de depreciação linear do que for investido (0 = não deprecia)
  residual_pct DOUBLE PRECISION NOT NULL DEFAULT 0,     -- valor residual, % do investido
  carencia INTEGER NOT NULL DEFAULT 0,      -- anos depois do investimento até começar a depreciar
  ativo INTEGER NOT NULL DEFAULT 1,
  criado_em TEXT NOT NULL
);

CREATE TABLE realizado_quantidades(        -- quantidade vendida de cada produto no período do realizado em andamento (para preço médio e comparação com o orçado)
  ano INTEGER NOT NULL,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  quantidade DOUBLE PRECISION NOT NULL DEFAULT 0,       -- na medida do produto (kg, litro ou unidade)
  PRIMARY KEY(ano, cultura_id)
);

CREATE TABLE versoes(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ano_base INTEGER NOT NULL,
  tipo TEXT NOT NULL CHECK(tipo IN ('orcado','reprojetado','revisao')),
  nome TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'rascunho' CHECK(status IN ('rascunho','aprovado')),
  horizonte INTEGER NOT NULL DEFAULT 5,   -- quantos anos projetar a partir do ano base
  data_inicio TEXT,                       -- início do período do orçamento (AAAA-MM-DD)
  data_fim TEXT,                          -- fim do período do orçamento (AAAA-MM-DD)
  divida_importacao_id INTEGER REFERENCES divida_importacoes(id),   -- base de dívidas usada pela versão
  origem_id INTEGER REFERENCES versoes(id),
  criado_em TEXT NOT NULL,
  aprovado_em TEXT,
  autor TEXT NOT NULL DEFAULT 'local'
);

CREATE TABLE anotacoes(                 -- marca-texto e comentário em um número de um relatório
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  tela TEXT NOT NULL,                       -- ex.: resultado
  chave TEXT NOT NULL,                      -- identifica o número na tela (cultura|linha|ano)
  cor TEXT NOT NULL DEFAULT '',             -- '' | amarelo | verde | vermelho
  comentario TEXT NOT NULL DEFAULT '',
  valor DOUBLE PRECISION,                               -- o número que a tela mostrava quando foi anotado (para avisar se mudar)
  validado INTEGER NOT NULL DEFAULT 0,      -- check: a anotação já foi conferida
  validado_em TEXT,
  validado_por TEXT,
  autor TEXT NOT NULL DEFAULT 'local',
  atualizado_em TEXT NOT NULL,
  PRIMARY KEY(versao_id, tela, chave)
);

CREATE TABLE areas_cultura(
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  ano INTEGER NOT NULL,
  area_ha DOUBLE PRECISION NOT NULL DEFAULT 0,           -- hectare físico, contado uma vez
  PRIMARY KEY(versao_id, cultura_id, ano)
);

CREATE TABLE capital_giro(                -- premissas de capital de giro digitadas, por versão, campo e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  campo TEXT NOT NULL,                      -- dias_receber, dias_insumos, pct_caixa...
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, campo, ano)
);

CREATE TABLE capital_giro_origem(         -- prazos calculados do balanço realizado (botão "atualizar prazos"); digitar de novo apaga a marca
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  campo TEXT NOT NULL,
  ano INTEGER NOT NULL,
  ano_realizado INTEGER NOT NULL,           -- último ano do período usado
  anos TEXT NOT NULL DEFAULT '',            -- todos os anos da média, ex.: 2023,2024,2025
  PRIMARY KEY(versao_id, campo, ano)
);

CREATE TABLE captacao_valores(             -- amortização e juros alterados à mão (substituem o calculado)
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  chave TEXT NOT NULL,                      -- cap-<id> | inv-<tipo_id>-<ano>
  campo TEXT NOT NULL,                      -- amort | juros
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL,
  PRIMARY KEY(versao_id, chave, campo, ano)
);

CREATE TABLE culturas_da_versao(      -- culturas que a empresa vai cultivar em cada versão
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  PRIMARY KEY(versao_id, cultura_id)
);

CREATE TABLE culturas_extras(             -- culturas adicionadas à mão em Produtividade ou Preços, sem área em 'Áreas por cultura'
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  tela TEXT NOT NULL,                       -- produtividade | precos
  PRIMARY KEY(versao_id, cultura_id, tela)
);

CREATE TABLE custos_cultura(           -- custo variável em R$ por hectare
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  grupo_id INTEGER NOT NULL REFERENCES grupos_custo(id),
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, cultura_id, grupo_id, ano)
);

CREATE TABLE custos_culturas(          -- culturas escolhidas na tela de Custos variáveis (só as que estão em Áreas)
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  PRIMARY KEY(versao_id, cultura_id)
);

CREATE TABLE custos_grupos_cultura(    -- grupos de custo que a versão usa em cada cultura (cada um vira uma linha)
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  grupo_id INTEGER NOT NULL REFERENCES grupos_custo(id),
  PRIMARY KEY(versao_id, cultura_id, grupo_id)
);

CREATE TABLE depreciacao_valores(          -- valores de depreciação alterados à mão (substituem o calculado) e a taxa média dos bens existentes
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  chave TEXT NOT NULL,                      -- taxa (ano 0) | existentes | tipo-<id>
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL,
  PRIMARY KEY(versao_id, chave, ano)
);

CREATE TABLE dre_padrao(                   -- premissas padronizadas das contas da DRE sem origem: % sobre uma base ou valor (R$ mil), por versão, conta e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  codigo TEXT NOT NULL,
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, codigo, ano)
);

CREATE TABLE dre_valores(               -- valores lançados nas linhas de entrada da DRE sintética, em R$ mil
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  codigo TEXT NOT NULL,
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, codigo, ano)
);

CREATE TABLE fazendas(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK(tipo IN ('propria','arrendada')),
  arrendador TEXT NOT NULL DEFAULT '',
  forma TEXT NOT NULL DEFAULT 'reais' CHECK(forma IN ('reais','produto')),
  cultura_id INTEGER REFERENCES culturas(id),   -- cultura usada no pagamento (quando forma='produto')
  observacao TEXT NOT NULL DEFAULT ''
);

CREATE TABLE financiamento_premissas(      -- taxa, prazo e carência do financiamento dos investimentos, por versão e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  campo TEXT NOT NULL,                      -- taxa | prazo | carencia
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, campo, ano)
);

CREATE TABLE giro_auto_premissas(          -- taxa da dívida de giro automática, por versão e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  campo TEXT NOT NULL,                      -- origem (0 digitar, 1 média das captações de custeio, 2 média das de capital de giro) | taxa (% a.a.)
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, campo, ano)
);

CREATE TABLE indicadores_metas(            -- limite (mínimo ou máximo) de cada indicador financeiro, por versão e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  indicador TEXT NOT NULL,
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL,
  PRIMARY KEY(versao_id, indicador, ano)
);

CREATE TABLE investimento_excluidos(       -- tipos que NÃO fazem parte do orçamento de uma versão (por padrão todo tipo ativo entra)
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  tipo_id INTEGER NOT NULL REFERENCES investimento_tipos(id),
  PRIMARY KEY(versao_id, tipo_id)
);

CREATE TABLE investimento_valores(         -- valores digitados por versão, tipo, campo e ano (R$ mil)
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  tipo_id INTEGER NOT NULL REFERENCES investimento_tipos(id),
  campo TEXT NOT NULL,                      -- saldo_ini (só no 1º ano) | novo | a_carregar | financiado (parte do investido do ano que é financiada)
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, tipo_id, campo, ano)
);

CREATE TABLE novas_captacoes(              -- captações novas de custeio e capital de giro, por versão (investimento nasce na tela Investimentos)
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  nome TEXT NOT NULL,
  tipo TEXT NOT NULL,                       -- custeio | capital_giro
  ano INTEGER NOT NULL,                     -- ano em que o dinheiro entra (meio do ano)
  valor DOUBLE PRECISION NOT NULL,                      -- R$ mil
  taxa DOUBLE PRECISION NOT NULL DEFAULT 0,             -- % ao ano
  prazo INTEGER NOT NULL DEFAULT 1,         -- parcelas anuais de principal
  carencia INTEGER NOT NULL DEFAULT 0       -- anos sem amortizar depois do ano da captação
);

CREATE TABLE patrimonio_valores(           -- premissas do patrimônio líquido por versão, campo e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  campo TEXT NOT NULL,                      -- dist_pct | dist_valor | aporte | ajuste
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, campo, ano)
);

CREATE TABLE pecuaria_leite(              -- produtividade pecuária (leite) por versão e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  ano INTEGER NOT NULL,
  animais DOUBLE PRECISION NOT NULL DEFAULT 0,          -- total de animais em lactação (uni)
  kg_animal_dia DOUBLE PRECISION NOT NULL DEFAULT 0,    -- produtividade diária por animal (kg/dia)
  PRIMARY KEY(versao_id, ano)
);

CREATE TABLE precos(
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  ano INTEGER NOT NULL,
  preco DOUBLE PRECISION NOT NULL DEFAULT 0,          -- valor padrão, em R$ por embalagem padrão (ou por kg/litro, se não houver)
  PRIMARY KEY(versao_id, cultura_id, ano)
);

CREATE TABLE precos_venda(           -- preço de venda: R$ por kg (ou por litro); separado do valor padrão de Arrendamentos
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  ano INTEGER NOT NULL,
  preco DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, cultura_id, ano)
);

CREATE TABLE prem_culturas(            -- culturas escolhidas na tela Premissas de culturas (só as de Áreas)
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  PRIMARY KEY(versao_id, cultura_id)
);

CREATE TABLE prem_itens(               -- tipos de premissa vinculados a cada cultura (cada um vira uma linha)
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  tipo TEXT NOT NULL,
  PRIMARY KEY(versao_id, cultura_id, tipo)
);

CREATE TABLE prem_valores(
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  tipo TEXT NOT NULL,
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, cultura_id, tipo, ano)
);

CREATE TABLE premissas_dem_itens(        -- premissas cadastradas que estão em uso (adicionadas à aba) em cada versão
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  premissa_id INTEGER NOT NULL REFERENCES premissas_dem(id),
  PRIMARY KEY(versao_id, premissa_id)
);

CREATE TABLE premissas_dem_valores(      -- valor digitado por versão e ano, em R$ mil
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  premissa_id INTEGER NOT NULL REFERENCES premissas_dem(id),
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, premissa_id, ano)
);

CREATE TABLE produtividade(
  versao_id INTEGER NOT NULL REFERENCES versoes(id) ON DELETE CASCADE,
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,     -- por hectare, na embalagem padrão da cultura (ou em kg/litro, se não houver)
  PRIMARY KEY(versao_id, cultura_id, ano)
);

CREATE TABLE rebanho_valores(              -- movimentação do rebanho dos produtos com estoque em gado de corte, por versão, produto, campo e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  cultura_id INTEGER NOT NULL REFERENCES culturas(id),
  campo TEXT NOT NULL,                      -- saldo_ini e valor_ini (só no 1º ano: cabeças e R$) | compras | nascimentos | mortes | vendas (cabeças)
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, cultura_id, campo, ano)
);

CREATE TABLE transportadora_valores(      -- premissas da transportadora (caminhões, km, preço por km, custos por km), por versão, campo e ano
  versao_id INTEGER NOT NULL REFERENCES versoes(id),
  campo TEXT NOT NULL,
  ano INTEGER NOT NULL,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY(versao_id, campo, ano)
);

CREATE TABLE fazenda_anos(
  fazenda_id INTEGER NOT NULL REFERENCES fazendas(id) ON DELETE CASCADE,
  ano INTEGER NOT NULL,
  area_ha DOUBLE PRECISION NOT NULL DEFAULT 0,
  valor DOUBLE PRECISION NOT NULL DEFAULT 0,          -- R$/ha (forma=reais) ou sacas/ha (forma=produto)
  PRIMARY KEY(fazenda_id, ano)
);

CREATE TABLE parcelas(
  fazenda_id INTEGER NOT NULL REFERENCES fazendas(id) ON DELETE CASCADE,
  mes INTEGER NOT NULL CHECK(mes BETWEEN 1 AND 12),
  percentual DOUBLE PRECISION NOT NULL,
  PRIMARY KEY(fazenda_id, mes)
);

CREATE INDEX ix_fazendas_versao ON fazendas(versao_id);
CREATE INDEX ix_titulos_imp ON divida_titulos(importacao_id, situacao);

